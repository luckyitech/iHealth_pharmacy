#!/usr/bin/env bash
# Writes the legacy schema (no data) to apps/api/db/sql/schema/legacy-schema.sql for tests and CI.
# Reads from the legacy server only. AUTO_INCREMENT counters and definers are stripped,
# so the file has no row data and the same schema always gives the same file.
source "$(dirname "$0")/lib.sh"

load_env
mkdir -p "$(dirname "${SCHEMA_FILE}")"

log "Dumping schema of ${LEGACY_DB_HOST}:${LEGACY_DB_PORT}/${LEGACY_DB_NAME}"
{
  echo "-- Legacy iHealth schema (structure only, no data)."
  echo "-- Generated by scripts/db/dump-test-schema.sh. Do not edit by hand."
  legacy_dump --no-data --routines --triggers --events --skip-dump-date --skip-comments \
    "${LEGACY_DB_NAME}"
} | strip_definers | sed -E 's/ AUTO_INCREMENT=[0-9]+//' >"${SCHEMA_FILE}"

log "Wrote ${SCHEMA_FILE} ($(wc -l <"${SCHEMA_FILE}" | tr -d ' ') lines)"
