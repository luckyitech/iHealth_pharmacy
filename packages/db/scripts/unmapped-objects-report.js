/**
 * Writes docs/db/unmapped-objects.md: the legacy database objects that the Prisma client does not model
 * (views, stored procedures and functions, triggers, events), plus the models Prisma had to ignore or
 * could only partly describe. Reads information_schema only.
 *
 *   node scripts/unmapped-objects-report.js   # uses TEST_DATABASE_URL (falls back to DATABASE_URL)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { config as loadEnv } from 'dotenv';
import mariadb from 'mariadb';

const here = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(here, '..');
const repoRoot = path.resolve(packageRoot, '../..');
const reportFile = path.join(repoRoot, 'docs/db/unmapped-objects.md');
const schemaFile = path.join(packageRoot, 'prisma/schema.prisma');
loadEnv({ path: path.join(repoRoot, '.env'), quiet: true });

/**
 * @typedef {{ name: string }} ViewRow
 * @typedef {{ name: string, type: 'PROCEDURE' | 'FUNCTION' }} RoutineRow
 * @typedef {{ name: string, tableName: string, timing: string, event: string }} TriggerRow
 * @typedef {{ name: string, status: string, intervalValue: string | null, intervalField: string | null }} EventRow
 * @typedef {{ views: ViewRow[], routines: RoutineRow[], triggers: TriggerRow[], events: EventRow[] }} Catalog
 */

/**
 * @param {string} url
 * @returns {Promise<Catalog>}
 */
async function readCatalog(url) {
  const { hostname, port, username, password, pathname } = new URL(url);
  const schema = pathname.replace(/^\//, '');
  const connection = await mariadb.createConnection({
    host: hostname,
    port: Number(port || 3306),
    user: decodeURIComponent(username),
    password: decodeURIComponent(password),
  });
  try {
    const query = (/** @type {string} */ sql) => connection.query(sql, [schema]);
    return {
      views: await query(
        'SELECT TABLE_NAME AS name FROM information_schema.VIEWS WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME',
      ),
      routines: await query(
        `SELECT ROUTINE_NAME AS name, ROUTINE_TYPE AS type FROM information_schema.ROUTINES
         WHERE ROUTINE_SCHEMA = ? ORDER BY ROUTINE_TYPE, ROUTINE_NAME`,
      ),
      triggers: await query(
        `SELECT TRIGGER_NAME AS name, EVENT_OBJECT_TABLE AS tableName, ACTION_TIMING AS timing,
                EVENT_MANIPULATION AS event
         FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = ? ORDER BY EVENT_OBJECT_TABLE, TRIGGER_NAME`,
      ),
      events: await query(
        `SELECT EVENT_NAME AS name, STATUS AS status, INTERVAL_VALUE AS intervalValue, INTERVAL_FIELD AS intervalField
         FROM information_schema.EVENTS WHERE EVENT_SCHEMA = ? ORDER BY EVENT_NAME`,
      ),
    };
  } finally {
    await connection.end();
  }
}

/**
 * Collects the models Prisma marked as ignored and the fields it could not type.
 *
 * @param {string} schema
 * @returns {{ ignored: string[], unsupported: string[] }}
 */
function readSchemaGaps(schema) {
  const ignored = [];
  const unsupported = [];
  let current = '';
  let table = '';
  for (const line of schema.split('\n')) {
    const start = /^model\s+(\w+)\s*\{/.exec(line);
    if (start) {
      current = start[1];
      table = current;
    }
    const mapped = /@@map\("([^"]+)"\)/.exec(line);
    if (mapped) table = mapped[1];
    if (/^\s*@@ignore/.test(line)) ignored.push(current);
    const field = /^\s*(\w+)\s+Unsupported\("([^"]+)"\)/.exec(line);
    if (field) unsupported.push(`${current}.${field[1]} (${field[2]})`);
    if (/^\}/.test(line) && ignored.at(-1) === current && table !== current) {
      ignored[ignored.length - 1] = `${current} (\`${table}\`)`;
    }
  }
  return { ignored, unsupported };
}

const url = process.env.TEST_DATABASE_URL ?? process.env.DATABASE_URL;
if (!url) throw new Error('Set TEST_DATABASE_URL (or DATABASE_URL).');

const catalog = await readCatalog(url);
const gaps = readSchemaGaps(readFileSync(schemaFile, 'utf8'));
const list = (/** @type {string[]} */ items) =>
  items.length ? items.map((item) => `- ${item}`).join('\n') : '_None._';

const report = `# Legacy database objects outside the Prisma client

Generated by \`npm run db:report -w @ihealth/db\` from the reference schema. Do not edit by hand.

Prisma models tables only. The objects below stay in MySQL exactly as the legacy system defines them.
Repositories reach them through parameterised raw queries (\`prisma.$queryRaw\`) and document each one when they first use it.

## Summary

| Object | Count |
| --- | --- |
| Views | ${catalog.views.length} |
| Stored procedures | ${catalog.routines.filter((r) => r.type === 'PROCEDURE').length} |
| Stored functions | ${catalog.routines.filter((r) => r.type === 'FUNCTION').length} |
| Triggers | ${catalog.triggers.length} |
| Events | ${catalog.events.length} |
| Tables ignored by Prisma (no unique identifier) | ${gaps.ignored.length} |
| Columns with unsupported types | ${gaps.unsupported.length} |

## Triggers

Triggers fire on writes made through Prisma too. Services that write to these tables must account for their side effects.

| Table | Trigger | When |
| --- | --- | --- |
${catalog.triggers.map((t) => `| \`${t.tableName}\` | \`${t.name}\` | ${t.timing} ${t.event} |`).join('\n')}

## Events (scheduled jobs)

| Event | Status | Every |
| --- | --- | --- |
${catalog.events.map((e) => `| \`${e.name}\` | ${e.status} | ${e.intervalValue ?? ''} ${e.intervalField ?? ''} |`).join('\n')}

## Tables ignored by Prisma

These tables have no primary key or unique index, so Prisma cannot read or write them through models.
They can only be used with raw queries.

${list(gaps.ignored)}

## Columns with unsupported types

${list(gaps.unsupported)}

## Stored procedures

${list(catalog.routines.filter((r) => r.type === 'PROCEDURE').map((r) => `\`${r.name}\``))}

## Stored functions

${list(catalog.routines.filter((r) => r.type === 'FUNCTION').map((r) => `\`${r.name}\``))}

## Views

${list(catalog.views.map((v) => `\`${v.name}\``))}
`;

mkdirSync(path.dirname(reportFile), { recursive: true });
writeFileSync(reportFile, report);
process.stdout.write(`Wrote ${path.relative(repoRoot, reportFile)}\n`);
