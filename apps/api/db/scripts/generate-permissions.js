/**
 * Regenerates the permission constants (packages/shared/src/permissions/definitions.js) and the matching
 * reference seed (sql/seed/01-pharma-access.sql) from the legacy `pharma_access` table. Read-only.
 *
 *   node scripts/generate-permissions.js   # uses DATABASE_URL (a copy of the legacy database)
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { config as loadEnv } from 'dotenv';
import mariadb from 'mariadb';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../../../..');
const definitionsFile = path.join(repoRoot, 'packages/shared/src/permissions/definitions.js');
const seedFile = path.join(repoRoot, 'apps/api/db/sql/seed/01-pharma-access.sql');
loadEnv({ path: path.join(repoRoot, '.env'), quiet: true });

/**
 * @typedef {{ id: number, group: string, name: string, activeS: string | null }} AccessRow
 */

/**
 * `Reports-Finance` + `Credit Note` -> `REPORTS_FINANCE_CREDIT_NOTE`
 *
 * @param {string} group
 * @param {string} name
 * @returns {string}
 */
export function permissionKey(group, name) {
  return `${group}_${name}`
    .toUpperCase()
    .replace(/&/g, ' AND ')
    .replace(/[^A-Z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
}

/**
 * @param {string} value
 * @returns {string}
 */
const sqlString = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;

const url = process.env.DATABASE_URL;
if (!url) throw new Error('Set DATABASE_URL to a copy of the legacy database.');
const { hostname, port, username, password, pathname } = new URL(url);
const connection = await mariadb.createConnection({
  host: hostname,
  port: Number(port || 3306),
  user: decodeURIComponent(username),
  password: decodeURIComponent(password),
  database: pathname.replace(/^\//, ''),
});
/** @type {AccessRow[]} */
const rows = await connection.query(
  `SELECT PHARMA_ACCESS_ID AS id, ACCESS_CD AS \`group\`, ACCESS_NAME AS name, ACTIVE_S AS activeS
   FROM pharma_access ORDER BY PHARMA_ACCESS_ID`,
);
await connection.end();

const keys = new Set();
const entries = rows.map((row) => {
  const key = permissionKey(row.group, row.name);
  if (keys.has(key)) throw new Error(`Two permissions map to the key ${key}`);
  keys.add(key);
  return `  ${key}: Object.freeze({ id: ${row.id}, group: ${JSON.stringify(row.group)}, name: ${JSON.stringify(row.name)}, active: ${row.activeS === 'Y'} }),`;
});

writeFileSync(
  definitionsFile,
  `// Generated from the legacy \`pharma_access\` table. Ids, groups and names are copied exactly, typos included,
// so they match production. Regenerate with \`npm run permissions:generate -w @ihealth/api\`.

/**
 * @typedef {object} PermissionDefinition
 * @property {number} id \`PHARMA_ACCESS_ID\` in the legacy database.
 * @property {string} group \`ACCESS_CD\` (the menu group in the legacy UI).
 * @property {string} name \`ACCESS_NAME\`.
 * @property {boolean} active \`ACTIVE_S = 'Y'\` when the list was generated.
 */

export const PERMISSIONS = Object.freeze({
${entries.join('\n')}
});
`,
);

writeFileSync(
  seedFile,
  `-- Legacy permission catalogue (reference data, not personal data). Generated by
-- \`npm run permissions:generate -w @ihealth/api\`; keep in sync with packages/shared/src/permissions/definitions.js.
INSERT INTO pharma_access (PHARMA_ACCESS_ID, ACCESS_CD, ACCESS_NAME, ACTIVE_S, CREATION_USER_ID) VALUES
${rows.map((row) => `  (${row.id}, ${sqlString(row.group)}, ${sqlString(row.name)}, ${sqlString(row.activeS ?? 'Y')}, 'seed')`).join(',\n')};
`,
);
process.stdout.write(`Wrote ${rows.length} permissions\n`);
